const I18n = {
  lang: 'es',

  load() {
    let lang = localStorage.getItem(LANG_KEY);
    if (!lang || SUPPORTED_LANGS.indexOf(lang) === -1) lang = detectDefaultLang();
    this.lang = lang;
    document.documentElement.lang = lang;
    return lang;
  },

  set(lang) {
    if (SUPPORTED_LANGS.indexOf(lang) === -1) return;
    this.lang = lang;
    localStorage.setItem(LANG_KEY, lang);
    document.documentElement.lang = lang;
    document.querySelectorAll('select.lang-select').forEach((sel) => {
      sel.value = lang;
    });
    if (typeof onLangChange === 'function') onLangChange();
  },

  t(key, ...args) {
    const dict = STRINGS[this.lang] || STRINGS.es;
    const val = dict[key] !== undefined ? dict[key] : STRINGS.es[key];
    return typeof val === 'function' ? val(...args) : val;
  },
};

I18n.load();

// Selector de idioma reutilizable (cliente y admin). Devuelve el elemento <select>.
function renderLangSelect(container) {
  const select = document.createElement('select');
  select.className = 'lang-select';
  select.setAttribute('aria-label', 'Idioma / Language / 言語 / Idioma');
  SUPPORTED_LANGS.forEach((code) => {
    const opt = document.createElement('option');
    opt.value = code;
    opt.textContent = LANG_LABELS[code];
    if (code === I18n.lang) opt.selected = true;
    select.appendChild(opt);
  });
  select.addEventListener('change', () => I18n.set(select.value));
  container.appendChild(select);
  return select;
}
